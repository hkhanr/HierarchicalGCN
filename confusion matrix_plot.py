import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import os
import sys


def visualize_confusion_matrix(file_path, num_classes=60, title=None):
    """
    Reads the confusion matrix data from the BlockGCN CSV output and plots it as a heatmap.

    The CSV file format:
    Row 1: Accuracy for each class (ignored for the matrix visualization).
    Rows 2+: The raw confusion matrix (Counts).
    """

    # --- 1. Load Data ---
    if not os.path.exists(file_path):
        print(f"Error: File not found at {file_path}")
        sys.exit(1)

    print(f"Loading confusion matrix data from: {file_path}")

    # Read the data, skipping the first row (which contains the per-class accuracy)
    # The raw confusion matrix starts at index 1 of the CSV.
    try:
        df = pd.read_csv(file_path, header=None)

        # Extract the raw confusion matrix (all rows after the first)
        raw_cm = df.iloc[1:].values

    except Exception as e:
        print(f"Error reading or processing CSV file: {e}")
        sys.exit(1)

    # --- 2. Calculate Normalized Matrix (Recall) ---
    # Normalize by the true class count (rows) to show recall/accuracy for each class
    cm_normalized = raw_cm.astype('float') / raw_cm.sum(axis=1)[:, np.newaxis]

    # Handle NaN values (which occur if a true class has zero samples in the test set)
    cm_normalized = np.nan_to_num(cm_normalized)

    # --- 3. Setup Plotting ---
    # Generate human-readable class names for NTU-60 (A001, A002, ...)
    class_names = [f'A{i:03d}' for i in range(1, num_classes + 1)]

    if title is None:
        title = f'Confusion Matrix'

    # Adjust figure size based on the number of classes
    fig_size = max(10, num_classes / 5)
    plt.figure(figsize=(fig_size, fig_size))

    # --- 4. Plot Heatmap ---
    sns.heatmap(
        cm_normalized,
        annot=False,  # Set to True if you want numbers on every cell (can be messy for 60 classes)
        fmt='.2f',
        cmap='Blues',
        xticklabels=class_names,
        yticklabels=class_names,
        linecolor='gray',
        linewidths=0.0
    )

    plt.title(title, fontsize=20)
    plt.ylabel('True Label (Activity Class)', fontsize=16)
    plt.xlabel('Predicted Label (Activity Class)', fontsize=16)
    # plt.grid(False)

    # Ensure all labels are visible for large plots
    plt.xticks(rotation=90)
    plt.yticks(rotation=0)
    plt.tight_layout()

    # Save the plot
    output_png_path = file_path.replace('.csv', '_confusion_matrix.png')
    plt.savefig(output_png_path)
    print(f"\n✅ Confusion Matrix saved to: {output_png_path}")
    # plt.show() # Uncomment to display the plot immediately


